import { Prisma } from '@prisma/client';
import { prisma } from '../../lib/prisma';
import { DATA_TABLES } from './tables';

type Db = Prisma.TransactionClient | typeof prisma;

/**
 * Data tables that already hold rows. Demo data may only be generated when this is empty: the
 * exclusive mode deletes demo data by emptying every data table, so it must never coexist with
 * real transactions that existed before it.
 */
export async function findNonEmptyDataTables(db: Db = prisma): Promise<string[]> {
  // Table names come from a fixed constant list, never from input.
  const sql = DATA_TABLES.map((t) => `SELECT '${t}' AS t WHERE EXISTS (SELECT 1 FROM "${t}")`).join(' UNION ALL ');
  const rows = await db.$queryRawUnsafe<{ t: string }[]>(sql);
  return rows.map((r) => r.t).sort();
}

/** Data generated by the old generator (flagged [Dummy] parties) is still present. */
export async function hasLegacyDummyData(db: Db = prisma): Promise<boolean> {
  const party = await db.party.findFirst({ where: { isDummy: true }, select: { id: true } });
  return Boolean(party);
}

/** A demo batch exists (running, finished or failed half-way) and owns the data tables. */
export async function activeDemoBatch(db: Db = prisma) {
  return db.demoDataBatch.findFirst({ orderBy: { startedAt: 'desc' } });
}

/** Audit entities that are not business data and survive a demo wipe. */
const NON_BUSINESS_ENTITIES = ['settings', 'auth', 'notifications', 'users', 'roles', 'rbac', 'ai', 'backup', 'fiscal-years', 'system-accounts', 'tax'];

/**
 * Changes users made (not the demo generator) since the demo started. Deleting demo data empties
 * every data table, so these are lost too; the delete dialog shows the count before confirming.
 */
export async function countUserChangesSince(since: Date, db: Db = prisma): Promise<number> {
  return db.auditLog.count({
    where: {
      createdAt: { gte: since },
      OR: [{ via: null }, { via: { not: 'demo' } }],
      entityType: { notIn: NON_BUSINESS_ENTITIES },
    },
  });
}
